-- Initial setup for a new project; existing installations need their own migrations.
create table if not exists public.ezynotify (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  url text not null,
  "telegramID" text not null,
  keywords jsonb,
  reference text not null default '',
  "foundKeyword" jsonb not null default '[]'::jsonb,
  "Updates" jsonb not null default '[]'::jsonb,
  "checkUpdates" boolean not null default false,
  "isUpdated" boolean not null default false,
  "shouldContinueCheck" boolean not null default true,
  "shouldSendDetailedUpdates" boolean not null default false,
  completed boolean not null default false
);

alter table public.ezynotify enable row level security;
grant select, insert, update, delete on public.ezynotify to service_role;
grant usage, select on sequence public.ezynotify_id_seq to service_role;
