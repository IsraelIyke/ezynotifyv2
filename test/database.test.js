import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('legacy PostgreSQL migration, ownership, leases, atomic results and durable drafts',async(t)=>{
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create table ezynotify(id bigint generated by default as identity primary key, created_at timestamptz not null default now(),
      url text,keywords json,reference text,"isUpdated" boolean default false,uuid uuid default gen_random_uuid(),
      "foundKeyword" json,"telegramID" bigint,"shouldContinueCheck" boolean default false,"Updates" json,
      "shouldSendDetailedUpdates" boolean,"checkUpdates" boolean default false,completed boolean default false);
      insert into ezynotify(url,reference,"telegramID",keywords) values('https://example.com','Preserve me',123,'{"keywords":["news"]}');`);
    await db.exec(await readFile(new URL('../supabase/migrations/202610160001_monitoring_v3.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/202610160002_users_and_timezones.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/202610160003_admin_failure_alerts.sql',import.meta.url),'utf8'));
    await t.test('historical owners are backfilled without inflating active usage, and profile updates are idempotent',async()=>{
      let r=await db.query('select * from bot_usage_stats');assert.equal(r.rows[0].total_users,1);assert.equal(r.rows[0].active_last_24h,0);
      await db.query("select record_bot_user('123','{\"first_name\":\"Test\",\"username\":\"testuser\"}',12)");
      await db.query("select record_bot_user('123','{\"first_name\":\"Test\",\"username\":\"testuser\"}',12)");
      r=await db.query('select interaction_count from bot_users');assert.equal(Number(r.rows[0].interaction_count),1);
      r=await db.query('select * from bot_usage_stats');assert.equal(r.rows[0].active_last_24h,1);
    });
    await t.test('original rows survive json-to-jsonb migration',async()=>{
      const {rows}=await db.query('select reference,keywords,pg_typeof(keywords)::text as kind from ezynotify where id=1');
      assert.equal(rows[0].reference,'Preserve me');assert.deepEqual(rows[0].keywords,{keywords:['news']});assert.equal(rows[0].kind,'jsonb');
    });
    await t.test('manual check ownership and cooldown',async()=>{
      let r=await db.query("select request_monitor_check('1','999') as result");assert.equal(r.rows[0].result,'missing');
      r=await db.query("select request_monitor_check('1','123') as result");assert.equal(r.rows[0].result,'queued');
      r=await db.query("select request_monitor_check('1','123') as result");assert.equal(r.rows[0].result,'cooldown');
    });
    await t.test('claims are exclusive and a user edit invalidates an in-flight result',async()=>{
      const r=await db.query("select * from claim_monitors('worker-a',20,null)");assert.equal(r.rows.length,1);
      const competing=await db.query("select * from claim_monitors('worker-b',20,null)");assert.equal(competing.rows.length,0);
      await db.query("update ezynotify set title='User edit' where id=1");
      const result=await db.query("select finish_monitor('1','worker-a',$1,$2::jsonb,null,'[]') as saved",[r.rows[0].row_version,JSON.stringify({reference:'Stale browser result',last_status:'ok',next_check_at:new Date().toISOString()})]);
      assert.equal(result.rows[0].saved,false);
      assert.equal((await db.query('select reference from ezynotify where id=1')).rows[0].reference,'Preserve me');
    });
    await t.test('successful result queues notification in the same transaction, replay cannot duplicate it',async()=>{
      const r=await db.query("select * from claim_monitors('worker-c',20,null)");
      const params=[r.rows[0].row_version,JSON.stringify({reference:'New good content',last_status:'ok',failure_count:0,next_check_at:new Date(Date.now()+600000).toISOString()}),JSON.stringify({status:'changed',summary:'Changed'}),JSON.stringify([{channel:'main',payload:{text:'A change'}}])];
      const sql="select finish_monitor('1','worker-c',$1,$2::jsonb,$3::jsonb,$4::jsonb) as saved";
      assert.equal((await db.query(sql,params)).rows[0].saved,true);
      assert.equal((await db.query(sql,params)).rows[0].saved,false);
      assert.equal((await db.query('select count(*)::int as n from notification_outbox')).rows[0].n,1);
      assert.equal((await db.query('select count(*)::int as n from monitor_events')).rows[0].n,1);
    });
    await t.test('draft confirmation consumes the draft atomically and does not save twice',async()=>{
      await db.query("insert into bot_sessions(chat_id,draft) values('123',$1)",[JSON.stringify({nonce:'test',step:'review'})]);
      const fields={url:'https://example.com/new',title:'New monitor',checkUpdates:true,keywords:null,interval_minutes:30,shouldContinueCheck:true,shouldSendDetailedUpdates:true,fetch_config:{mode:'browser'}};
      const params=[JSON.stringify(fields)];
      const r=await db.query("select commit_bot_draft('123','test',$1::jsonb,null) as id",params);assert.ok(r.rows[0].id);
      await assert.rejects(db.query("select commit_bot_draft('123','test',$1::jsonb,null)",params));
      assert.equal((await db.query('select count(*)::int as n from ezynotify')).rows[0].n,2);
      assert.equal((await db.query('select count(*)::int as n from bot_sessions')).rows[0].n,0);
    });
    await t.test('runtime locks and Telegram update claims reject overlapping callers',async()=>{
      assert.equal((await db.query("select acquire_runtime_lock('dispatch','a',60) as ok")).rows[0].ok,true);
      assert.equal((await db.query("select acquire_runtime_lock('dispatch','b',60) as ok")).rows[0].ok,false);
      assert.equal((await db.query('select claim_bot_update(42) as ok')).rows[0].ok,true);
      assert.equal((await db.query('select claim_bot_update(42) as ok')).rows[0].ok,false);
    });
    await t.test('repeated failures queue separate admin alerts and privacy requests are idempotent',async()=>{
      await db.exec("insert into monitor_admin_settings(chat_id) values('999'); update ezynotify set url='https://example.com/private?token=secret' where id=1");
      for(let i=0;i<2;i++)await db.query("insert into monitor_events(monitor_id,status,summary) values('1','error','Blocked <test>')");
      await db.query("insert into monitor_events(monitor_id,status,summary) values('1','unchanged','Fine')");
      const alerts=(await db.query("select * from notification_outbox where channel='admin_failure'")).rows;
      assert.equal(alerts.length,2);assert.equal(alerts[0].chat_id,'999');
      assert.ok(alerts[0].payload.text.includes('&lt;test&gt;'));assert.ok(!alerts[0].payload.text.includes('secret'));
      assert.ok((await db.query("select * from claim_notifications('users',100)")).rows.every(x=>x.channel!=='admin_failure'));
      assert.equal((await db.query("select * from claim_admin_notifications('admin',20)")).rows.length,2);
      const a=(await db.query("select request_bot_privacy('123','deletion') id")).rows[0].id;
      assert.equal((await db.query("select request_bot_privacy('123','deletion') id")).rows[0].id,a);
      await db.exec('set role anon');
      await assert.rejects(db.query("select request_bot_privacy('123','access')"));
      await db.exec('reset role');
    });
    await t.test('public API roles cannot execute privileged worker functions',async()=>{
      await db.exec('set role anon');
      await assert.rejects(db.query("select claim_monitors('attacker',20,null)"));
      await db.exec('reset role');
    });
  } finally {await db.close();}
});
